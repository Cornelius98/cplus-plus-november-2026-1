#include <iostream>

using namespace std;

int main()
{
    //short - whole numbers
    short myShort = 100;
    cout << "Short: " << myShort << endl;

    //Integer - whole numbers
    int myInt = 25242425;
    cout << "Int: " << myInt << endl;

    //Long - whole numbers
    long long myLong = 2426245264;
    cout << "Long: " << myLong << endl;

    //Float - Decimal numcer or fraction,decimals 0 - 7
    float pie = 3.142f;
    cout << "Fraction: " << pie <<endl;

    //Double - decimal numcers, decimal digits 7 -15
    double myDouble = 0.1422642624252;
    cout << "Double: " << myDouble << endl;


    return 0;
}
